export function getInvestorsByType(type: InvestorType): InvestorProfile[] {
  return EAST_AFRICA_INVESTORS.filter(i => i.type === type);
}

export function getInvestorsByStatus(status: ContactStatus): InvestorProfile[] {
  return EAST_AFRICA_INVESTORS.filter(i => i.contactStatus === status);
}

export function getInvestorsByTier(tier: InvestorTier): InvestorProfile[] {
  return EAST_AFRICA_INVESTORS.filter(i => i.tier === tier);
}

export function getInvestorsByTicket(maxUsd: number): InvestorProfile[] {
  return EAST_AFRICA_INVESTORS.filter(i => {
    const match = i.ticketRangeUsd.match(/(\d+)K/);
    if (!match) return false;
    return parseInt(match[1], 10) <= maxUsd / 1000;
  });
}

